// Command crs-setup performs a ONE-TIME (prototype-only) honest setup for
// the Groth-Sahai SXDH soundness CRS. It writes no trapdoor and refuses to
// overwrite an existing installed CRS. For production use a reviewed ceremony.
package main

import (
	"crypto/sha256"
	"encoding/hex"
	"fmt"
	"go/format"
	"log"
	"os"
	"path/filepath"

	"hackaton2026/crypto/capture"
)

func main() {
	if capture.GlobalCRSConfigured() {
		log.Fatal("refusing to regenerate configured global CRS: it must be reused by every device and PCC")
	}
	crs, err := capture.NewCaptureCRSSoundness()
	if err != nil {
		log.Fatal(err)
	}
	data, err := crs.MarshalBinary()
	if err != nil {
		log.Fatal(err)
	}
	digest := sha256.Sum256(data)
	dest := filepath.Join("capture", "global_crs_generated.go")
	source := fmt.Sprintf(`package capture

// Code generated by cmd/crs-setup after a ONE-TIME honest setup.
// Public points ONLY; no extraction/simulation trapdoor is stored here.
// Version: %s
const globalCRSHex = %q
const globalCRSSHA256 = %q
`, capture.GlobalCaptureCRSVersion, hex.EncodeToString(data), hex.EncodeToString(digest[:]))
	formatted, err := format.Source([]byte(source))
	if err != nil {
		log.Fatal(err)
	}
	temporary := dest + ".tmp"
	if err := os.WriteFile(temporary, formatted, 0600); err != nil {
		log.Fatal(err)
	}
	defer os.Remove(temporary)
	if err := os.Rename(temporary, dest); err != nil {
		log.Fatal(err)
	}
	fmt.Printf("CRS installed at %s\n", dest)
	fmt.Printf("SHA-256: %x\n", digest)
	fmt.Println("IMPORTANT: copy the same generated file to ALL device and PCC builds. Never rerun per device.")
	fmt.Println("SECURITY: this local prototype ceremony is trusted; consider a reviewed multiparty ceremony for production.")
}

package capture

// Fine-tuned Groth-Sahai SXDH proof for two JR-certified hidden Schnorr attestations.
// Two linear Jutla-Roy PPEs have nontrivial base-element targets e(P1,-C1).
// They are proved directly using 2 G2 elements each (Escala-Groth 2014).
// Two nonlinear Jutla-Roy PPEs and two Schnorr MSMs retain GS proofs.
// This is proof-of-concept code: the device's hardware provenance is an
// assumption external to these algebraic proof equations.

import (
	"crypto/sha256"
	"crypto/subtle"
	"encoding/hex"
	"errors"
	"fmt"

	blst "github.com/supranational/blst/bindings/go"
)

const (
	CaptureG1WitnessCount     = 12
	CaptureG2WitnessCount     = 2
	CaptureScalarWitnessCount = 2 // hidden Schnorr responses z_s,z_e; delta fixed.
	CapturePPECount           = 4
	CaptureMSM1Count          = 2
	CaptureMSM2Count          = 0 // no auxiliary MSMs
)

const (
	xE1 = iota
	xE2
	xRho1
	xRhoHat1
	xPsi1
	xGamma1
	xPi1
	xRho2
	xRhoHat2
	xPsi2
	xGamma2
	xPi2
)
const (
	yTau1 = iota
	yTau2
)
const (
	scZSensor = iota
	scZEnclave
	scDelta
)

type gsVec1 [2]blst.P1
type gsVec2 [2]blst.P2

func (v *gsVec1) addScaled(w gsVec1, s *blst.Scalar, sign int8) {
	for k := 0; k < 2; k++ {
		t := w[k]
		t.MultAssign(s)
		if sign < 0 {
			v[k].SubAssign(&t)
		} else {
			v[k].AddAssign(&t)
		}
	}
}
func (v *gsVec2) addScaled(w gsVec2, s *blst.Scalar, sign int8) {
	for k := 0; k < 2; k++ {
		t := w[k]
		t.MultAssign(s)
		if sign < 0 {
			v[k].SubAssign(&t)
		} else {
			v[k].AddAssign(&t)
		}
	}
}
func (v *gsVec1) addPlain(p *blst.P1, scalar *blst.Scalar, sign int8) {
	t := *p
	t.MultAssign(scalar)
	if sign < 0 {
		v[1].SubAssign(&t)
	} else {
		v[1].AddAssign(&t)
	}
}
func (v *gsVec2) addPlain(p *blst.P2, scalar *blst.Scalar, sign int8) {
	t := *p
	t.MultAssign(scalar)
	if sign < 0 {
		v[1].SubAssign(&t)
	} else {
		v[1].AddAssign(&t)
	}
}
func gsIota1(p blst.P1) gsVec1                { return gsVec1{blst.P1{}, p} }
func gsIota2(p blst.P2) gsVec2                { return gsVec2{blst.P2{}, p} }
func gsP1FromAff(p *blst.P1Affine) blst.P1    { var q blst.P1; q.FromAffine(p); return q }
func gsP2FromAff(p *blst.P2Affine) blst.P2    { var q blst.P2; q.FromAffine(p); return q }
func gsNeg1(x blst.P1) blst.P1                { var z blst.P1; z.SubAssign(&x); return z }
func gsNeg2(x blst.P2) blst.P2                { var z blst.P2; z.SubAssign(&x); return z }
func gsProduct(a, b *blst.Scalar) blst.Scalar { x := *a; x.MulAssign(b); return x }

// CaptureCRS must be generated ONCE in the Groth-Sahai SXDH soundness
// distribution, distributed as a common public constant, and pinned by PCC.
// Sampling eight unrelated hash-to-curve points would change the commitment
// mode and invalidate the extraction argument required by our security model.
// The globally pinned CRS is generated by the separate cmd/crs-setup tool.
// CAUTION: the ceremony MUST NOT preserve the setup trapdoors; the 576 public
// bytes and their SHA-256 fingerprint alone do not prove a safe ceremony.
type CaptureCRS struct {
	U1, U2 gsVec1
	V1, V2 gsVec2
}

const GlobalCaptureCRSVersion = "HACKATON2026_JR_SCHNORR_GS_SXDH_SOUNDNESS_V1"

// NewCaptureCRSSoundness is SETUP-ONLY and returns fresh secret-dependent
// parameters. Never run it per photo/device or use a prover-chosen CRS.
func NewCaptureCRSSoundness() (CaptureCRS, error) {
	var crs CaptureCRS
	crs.U1[0] = *blst.P1Generator()
	RandomG1Point(&crs.U1[1])
	crs.V1[0] = *blst.P2Generator()
	RandomG2Point(&crs.V1[1])
	var r1, r2 blst.Scalar
	RandomScalar(&r1)
	RandomScalar(&r2)
	defer r1.Zeroize()
	defer r2.Zeroize()
	for i := 0; i < 2; i++ {
		crs.U2[i] = crs.U1[i]
		crs.U2[i].MultAssign(&r1)
		crs.V2[i] = crs.V1[i]
		crs.V2[i].MultAssign(&r2)
	}
	return crs, nil
}

// GlobalCRSConfigured indicates whether the one-time ceremony has completed
// for this build; run `go run ./cmd/crs-setup` exactly once for the prototype.
func GlobalCRSConfigured() bool { return globalCRSHex != "" && globalCRSSHA256 != "" }

// NewCaptureCRSGlobal reads the pinned, VERSIONED public CRS embedded in this
// source build. Every device and PCC must deploy the SAME generated file.
func NewCaptureCRSGlobal() (CaptureCRS, error) {
	var crs CaptureCRS
	if !GlobalCRSConfigured() {
		return crs, errors.New("global GS CRS not provisioned: run go run ./cmd/crs-setup once")
	}
	b, err := hex.DecodeString(globalCRSHex)
	if err != nil {
		return crs, fmt.Errorf("bad embedded CRS: %w", err)
	}
	if len(b) != CaptureCRSCompressedSize {
		return crs, errors.New("wrong global CRS byte length")
	}
	expected, err := hex.DecodeString(globalCRSSHA256)
	if err != nil || len(expected) != sha256.Size {
		return crs, errors.New("invalid embedded CRS fingerprint")
	}
	digest := sha256.Sum256(b)
	if subtle.ConstantTimeCompare(digest[:], expected) != 1 {
		return crs, errors.New("embedded CRS fingerprint mismatch")
	}
	if err := crs.UnmarshalBinary(b); err != nil {
		return CaptureCRS{}, err
	}
	if err := captureValidateCRSPoints(crs); err != nil {
		return CaptureCRS{}, err
	}
	return crs, nil
}

// ValidateGlobalCaptureCRS rejects custom, user-supplied, or altered CRS
// values, even when their points are individually valid.
func ValidateGlobalCaptureCRS(crs CaptureCRS) error {
	canonical, err := NewCaptureCRSGlobal()
	if err != nil {
		return err
	}
	a, err := crs.MarshalBinary()
	if err != nil {
		return err
	}
	b, err := canonical.MarshalBinary()
	if err != nil {
		return err
	}
	if subtle.ConstantTimeCompare(a, b) != 1 {
		return errors.New("CRS does not match the globally pinned SXDH soundness CRS")
	}
	return nil
}

func GlobalCaptureCRSFingerprint() ([32]byte, error) {
	crs, err := NewCaptureCRSGlobal()
	if err != nil {
		return [32]byte{}, err
	}
	b, err := crs.MarshalBinary()
	if err != nil {
		return [32]byte{}, err
	}
	return sha256.Sum256(b), nil
}
func (c CaptureCRS) w1() gsVec1 { w := c.U2; w[1].AddAssign(blst.P1Generator()); return w }
func (c CaptureCRS) w2() gsVec2 { w := c.V2; w[1].AddAssign(blst.P2Generator()); return w }

// CaptureStatement contains the public facts the NIZK is bound to.
type CaptureStatement struct {
	M        blst.P1Affine
	SensorR  blst.P1Affine
	EnclaveR blst.P1Affine
	VK1, VK2 Vk
}
type CaptureWitness struct {
	E1, E2            blst.P1
	Sig1, Sig2        Signature
	ZSensor, ZEnclave blst.Scalar
}

// Witness: E1,E2, and the 5 G1 elements of each Jutla-Roy signature.
// Each JR signature contains (rho, rhoHat, psi, gamma, pi) in G1^5 and
// tau in G2. The same committed E1,E2 are used by the masking MSMs.
func makeCaptureWitnessVectors(st *CaptureStatement, w *CaptureWitness) ([12]blst.P1, [2]blst.P2, [3]blst.Scalar, error) {
	var x [12]blst.P1
	var y [2]blst.P2
	var scal [3]blst.Scalar
	if st == nil || w == nil {
		return x, y, scal, errors.New("nil statement or witness")
	}
	if !w.Sig1.set || !w.Sig2.set || !st.VK1.set || !st.VK2.set {
		return x, y, scal, errors.New("missing JR signature or verification key")
	}
	if !w.ZSensor.Valid() || !w.ZEnclave.Valid() {
		return x, y, scal, errors.New("invalid Schnorr responses")
	}
	if !w.E1.ToAffine().InG1() || !w.E2.ToAffine().InG1() ||
		schnorrIdentity(w.E1.ToAffine()) || schnorrIdentity(w.E2.ToAffine()) {
		return x, y, scal, errors.New("invalid certified keys")
	}
	x[0], x[1] = w.E1, w.E2
	sigs := [2]Signature{w.Sig1, w.Sig2}
	for ca := 0; ca < 2; ca++ {
		off := 2 + 5*ca
		x[off] = gsP1FromAff(&sigs[ca].rho)
		x[off+1] = gsP1FromAff(&sigs[ca].rhoHat)
		x[off+2] = gsP1FromAff(&sigs[ca].psi)
		x[off+3] = gsP1FromAff(&sigs[ca].gamma)
		x[off+4] = gsP1FromAff(&sigs[ca].pi)
		y[ca] = gsP2FromAff(&sigs[ca].tau)
	}
	scal[0], scal[1] = w.ZSensor, w.ZEnclave
	var oneBytes [32]byte
	oneBytes[31] = 1
	if scal[2].FromBEndian(oneBytes[:]) == nil {
		return x, y, scal, errors.New("cannot encode scalar 1")
	}
	return x, y, scal, nil
}

// Sparse coefficients are signed +/-1. All equation targets are identities.
// Linear PPEs are Jutla-Roy QA main equations: prod_i e(X_i, B_i)=e(P1, Target).
// This is the base-element case of Escala-Groth under SXDH.
// Nonlinear PPEs are Jutla-Roy tag consistency equations.
type gsPPE struct {
	A      [2]blst.P1
	B      [12]blst.P2
	Gamma  [12][2]int8
	Linear bool
	Target blst.P2
}
type gsGammaCoefficient struct {
	Scalar blst.Scalar
	Active bool
}
type gsMSM1 struct {
	A     [3]blst.P1
	Gamma [12][3]gsGammaCoefficient
}

func captureEquations(st *CaptureStatement) ([4]gsPPE, [2]gsMSM1, error) {
	var pp [4]gsPPE
	var msm [2]gsMSM1
	if st == nil || !st.VK1.set || !st.VK2.set {
		return pp, msm, errors.New("invalid statement keys")
	}
	if !st.M.InG1() || schnorrIdentity(&st.M) {
		return pp, msm, errors.New("invalid capture message")
	}
	if !st.SensorR.InG1() || schnorrIdentity(&st.SensorR) ||
		!st.EnclaveR.InG1() || schnorrIdentity(&st.EnclaveR) {
		return pp, msm, errors.New("invalid Schnorr public nonce")
	}
	cSensor, err := SensorChallenge(&st.M, &st.SensorR)
	if err != nil {
		return pp, msm, err
	}
	cEnclave, err := EnclaveChallenge(&st.M, &st.SensorR, &st.EnclaveR)
	if err != nil {
		return pp, msm, err
	}
	// z_s P1 - c_s E1 - delta R_s = O1, delta is fixed to 1 in real CRS.
	// z_e P1 - c_e E2 - delta R_e = O1.
	// The terms E_i*delta are handled by generic GS MSMs, with public
	// coefficients -c_i; both z_i are secret scalar GS witnesses.
	challenges := [2]blst.Scalar{cSensor, cEnclave}
	nonces := [2]blst.P1Affine{st.SensorR, st.EnclaveR}
	for i := 0; i < 2; i++ {
		msm[i].A[i] = *blst.P1Generator()
		nonce := gsP1FromAff(&nonces[i])
		msm[i].A[scDelta] = gsNeg1(nonce)
		var neg blst.Scalar
		neg.SubAssign(&challenges[i])
		msm[i].Gamma[i][scDelta] = gsGammaCoefficient{Scalar: neg, Active: true}
	}
	// JR main QA-NIZK equation:
	//   prod e((E_i, rho_i, rhoHat_i, psi_i, gamma_i), C0_i)
	//   * e(pi_i,-A_i) = e(P1,-C1_i).
	// JR tag equation:
	//   e(rho_i,tau_i) * e(psi_i,-P2) = 1.
	vks := [2]*Vk{&st.VK1, &st.VK2}
	for ca := 0; ca < 2; ca++ {
		vk := vks[ca]
		off := 2 + 5*ca
		pp[ca].Linear = true
		pp[ca].Target = gsNeg2(gsP2FromAff(&vk.c1))
		pp[ca].B[ca] = gsP2FromAff(&vk.c0[0])
		for j := 0; j < 4; j++ {
			pp[ca].B[off+j] = gsP2FromAff(&vk.c0[j+1])
		}
		pp[ca].B[off+4] = gsNeg2(gsP2FromAff(&vk.a))
		pp[2+ca].Gamma[off][ca] = 1                     // e(rho,tau)
		pp[2+ca].B[off+2] = gsNeg2(*blst.P2Generator()) // e(psi,-P2)
	}
	return pp, msm, nil
}

// First two JR PPE proofs store only Pi[0][0] and Pi[1][0] (two G2 points).
// The other two use the generic 4G1+4G2 proof.
type gsPPEProof struct {
	Pi    [2]gsVec2
	Theta [2]gsVec1
}
type gsMSM1Proof struct {
	Pi    [2]gsVec2
	Theta gsVec1
}
type CaptureProof struct {
	C          [12]gsVec1
	D          [2]gsVec2
	ScalarD    [2]gsVec2
	PPE        [4]gsPPEProof
	SchnorrMSM [2]gsMSM1Proof
	OpeningPoK gsOpeningPoK
}

func gsCommit1(x blst.P1, c CaptureCRS, r [2]blst.Scalar) gsVec1 {
	z := gsIota1(x)
	z.addScaled(c.U1, &r[0], 1)
	z.addScaled(c.U2, &r[1], 1)
	return z
}
func gsCommit2(y blst.P2, c CaptureCRS, s [2]blst.Scalar) gsVec2 {
	z := gsIota2(y)
	z.addScaled(c.V1, &s[0], 1)
	z.addScaled(c.V2, &s[1], 1)
	return z
}

// CaptureProve constructs Groth–Sahai commitments for four PPE + two MSM.
// The caller must protect the witness and the commitment randomness.
func CaptureProve(crs CaptureCRS, st *CaptureStatement, w *CaptureWitness) (CaptureProof, error) {
	var out CaptureProof
	if err := ValidateGlobalCaptureCRS(crs); err != nil {
		return out, err
	}
	x, y, scalars, err := makeCaptureWitnessVectors(st, w)
	if err != nil {
		return out, err
	}
	ppe, msm, err := captureEquations(st)
	if err != nil {
		return out, err
	}
	// Check originals first to fail closed on an inconsistent witness.
	if err := captureCheckWitness(st, w); err != nil {
		return out, err
	}
	var rho [12][2]blst.Scalar
	var eta [2][2]blst.Scalar
	var lambda [3]blst.Scalar
	defer func() {
		for i := range rho {
			for j := 0; j < 2; j++ {
				rho[i][j].Zeroize()
			}
		}
		for i := range eta {
			for j := 0; j < 2; j++ {
				eta[i][j].Zeroize()
			}
		}
		for i := range lambda {
			lambda[i].Zeroize()
		}
	}()
	for i := range rho {
		RandomScalar(&rho[i][0])
		RandomScalar(&rho[i][1])
		out.C[i] = gsCommit1(x[i], crs, rho[i])
	}
	for j := range eta {
		RandomScalar(&eta[j][0])
		RandomScalar(&eta[j][1])
		out.D[j] = gsCommit2(y[j], crs, eta[j])
	}
	w2 := crs.w2()
	for j := 0; j < 2; j++ {
		RandomScalar(&lambda[j])
		out.ScalarD[j].addScaled(w2, &scalars[j], 1)
		out.ScalarD[j].addScaled(crs.V1, &lambda[j], 1)
	}
	for i := 0; i < 4; i++ {
		out.PPE[i] = gsProvePPE(crs, ppe[i], x, y, rho, eta)
	}
	for i := 0; i < 2; i++ {
		out.SchnorrMSM[i] = gsProveSchnorr(crs, msm[i], x, scalars, rho, lambda)
	}
	out.OpeningPoK, err = proveOpeningKnowledge(crs, st, &out, scalars, lambda)
	if err != nil {
		return CaptureProof{}, err
	}
	return out, nil
}

func captureCheckWitness(st *CaptureStatement, w *CaptureWitness) error {
	m1 := w.E1.ToAffine()
	m2 := w.E2.ToAffine()
	ok, err := Verify(m1, &w.Sig1, &st.VK1)
	if err != nil {
		return err
	}
	if ok != 1 {
		return errors.New("invalid JR signature for E1")
	}
	ok, err = Verify(m2, &w.Sig2, &st.VK2)
	if err != nil {
		return err
	}
	if ok != 1 {
		return errors.New("invalid JR signature for E2")
	}
	att1 := SchnorrAttestation{R: st.SensorR, Z: w.ZSensor}
	att2 := SchnorrAttestation{R: st.EnclaveR, Z: w.ZEnclave}
	valid, err := VerifyLayerAttestation(LayerSensor, &st.M, nil, m1, &att1)
	if err != nil || !valid {
		return errors.New("invalid sensor Schnorr signature")
	}
	valid, err = VerifyLayerAttestation(LayerEnclave, &st.M, &st.SensorR, m2, &att2)
	if err != nil || !valid {
		return errors.New("invalid enclave Schnorr signature")
	}

	return nil
}

func gsProvePPE(crs CaptureCRS, eq gsPPE, x [12]blst.P1, y [2]blst.P2, rho [12][2]blst.Scalar, eta [2][2]blst.Scalar) gsPPEProof {
	var out gsPPEProof
	if eq.Linear {
		// Special linear/base-element PPE proof: 2 G2, zero G1.
		// Com(X_i) = iota(X_i) + rho_i0 U1 + rho_i1 U2.
		// pi_k = sum_i rho_ik B_i, k=0,1.
		for k := 0; k < 2; k++ {
			for i := 0; i < 12; i++ {
				p := eq.B[i]
				p.MultAssign(&rho[i][k])
				out.Pi[k][0].AddAssign(&p)
			}
		}
		return out
	}
	u := [2]gsVec1{crs.U1, crs.U2}
	v := [2]gsVec2{crs.V1, crs.V2}
	var t [2][2]blst.Scalar // t[row theta index][column pi index]
	for a := 0; a < 2; a++ {
		for b := 0; b < 2; b++ {
			RandomScalar(&t[a][b])
		}
	}
	defer func() {
		for a := 0; a < 2; a++ {
			for b := 0; b < 2; b++ {
				t[a][b].Zeroize()
			}
		}
	}()
	for k := 0; k < 2; k++ {
		for i := 0; i < 12; i++ {
			out.Pi[k].addPlain(&eq.B[i], &rho[i][k], 1)
			for j := 0; j < 2; j++ {
				if sign := eq.Gamma[i][j]; sign != 0 {
					out.Pi[k].addPlain(&y[j], &rho[i][k], sign)
					for l := 0; l < 2; l++ {
						tmp := gsProduct(&rho[i][k], &eta[j][l])
						out.Pi[k].addScaled(v[l], &tmp, sign)
						tmp.Zeroize()
					}
				}
			}
		}
		for l := 0; l < 2; l++ {
			out.Pi[k].addScaled(v[l], &t[l][k], -1)
		}
	}
	for l := 0; l < 2; l++ {
		for j := 0; j < 2; j++ {
			out.Theta[l].addPlain(&eq.A[j], &eta[j][l], 1)
			for i := 0; i < 12; i++ {
				if sign := eq.Gamma[i][j]; sign != 0 {
					out.Theta[l].addPlain(&x[i], &eta[j][l], sign)
				}
			}
		}
		for k := 0; k < 2; k++ {
			out.Theta[l].addScaled(u[k], &t[l][k], 1)
		}
	}
	return out
}
func gsProveSchnorr(crs CaptureCRS, eq gsMSM1, x [12]blst.P1, ys [3]blst.Scalar, rho [12][2]blst.Scalar, lambda [3]blst.Scalar) gsMSM1Proof {
	var out gsMSM1Proof
	u := [2]gsVec1{crs.U1, crs.U2}
	w2 := crs.w2()
	var t [2]blst.Scalar
	RandomScalar(&t[0])
	RandomScalar(&t[1])
	defer t[0].Zeroize()
	defer t[1].Zeroize()
	for k := 0; k < 2; k++ {
		for i := 0; i < 12; i++ {
			for j := 0; j < 3; j++ {
				if coeff := eq.Gamma[i][j]; coeff.Active {
					tmp := gsProduct(&rho[i][k], &ys[j])
					tmp.MulAssign(&coeff.Scalar)
					out.Pi[k].addScaled(w2, &tmp, 1)
					tmp.Zeroize()
					tmp = gsProduct(&rho[i][k], &lambda[j])
					tmp.MulAssign(&coeff.Scalar)
					out.Pi[k].addScaled(crs.V1, &tmp, 1)
					tmp.Zeroize()
				}
			}
		}
		out.Pi[k].addScaled(crs.V1, &t[k], -1)
		out.Theta.addScaled(u[k], &t[k], 1)
	}
	for j := 0; j < 3; j++ {
		out.Theta.addPlain(&eq.A[j], &lambda[j], 1)
		for i := 0; i < 12; i++ {
			if coeff := eq.Gamma[i][j]; coeff.Active {
				tmp := gsProduct(&lambda[j], &coeff.Scalar)
				out.Theta.addPlain(&x[i], &tmp, 1)
				tmp.Zeroize()
			}
		}
	}
	return out
}

// Each GS verification equation holds in GT^4 and is checked as four
// multi-pairing equalities. The verification never receives the witness.
type capturePairs struct {
	ps []blst.P1Affine
	qs []blst.P2Affine
}

func (a *capturePairs) add(p *blst.P1, q *blst.P2, sign int8) {
	var pZero blst.P1
	var qZero blst.P2
	if p == nil || q == nil || p.Equals(&pZero) || q.Equals(&qZero) {
		return
	}
	c := *p
	if sign < 0 {
		c = gsNeg1(c)
	}
	a.ps = append(a.ps, *c.ToAffine())
	a.qs = append(a.qs, *q.ToAffine())
}
func gsPairEqual(lhs, rhs capturePairs) bool {
	left := blst.Fp12One()
	right := blst.Fp12One()
	if len(lhs.qs) > 0 {
		left = *blst.Fp12MillerLoopN(lhs.qs, lhs.ps)
	}
	if len(rhs.qs) > 0 {
		right = *blst.Fp12MillerLoopN(rhs.qs, rhs.ps)
	}
	return blst.Fp12FinalVerify(&left, &right)
}

func gsVerifyPPE(crs CaptureCRS, eq gsPPE, proof gsPPEProof, c [12]gsVec1, d [2]gsVec2) bool {
	if eq.Linear {
		// Verify prod_i e(C_i,k, B_i) = e(U1_k, pi_0)
		// * e(U2_k, pi_1) * e(P1, Target)^[k==1].
		// Target=e(P1,c_CA[0]) is the permitted base-element target.
		for row := 0; row < 2; row++ {
			var lhs, rhs capturePairs
			for i := 0; i < 12; i++ {
				lhs.add(&c[i][row], &eq.B[i], 1)
			}
			rhs.add(&crs.U1[row], &proof.Pi[0][0], 1)
			rhs.add(&crs.U2[row], &proof.Pi[1][0], 1)
			if row == 1 {
				rhs.add(blst.P1Generator(), &eq.Target, 1)
			}
			if !gsPairEqual(lhs, rhs) {
				return false
			}
		}
		return true
	}
	for row := 0; row < 2; row++ {
		for col := 0; col < 2; col++ {
			var lhs, rhs capturePairs
			if row == 1 {
				for j := 0; j < 2; j++ {
					lhs.add(&eq.A[j], &d[j][col], 1)
				}
			}
			if col == 1 {
				for i := 0; i < 12; i++ {
					lhs.add(&c[i][row], &eq.B[i], 1)
				}
			}
			for i := 0; i < 12; i++ {
				for j := 0; j < 2; j++ {
					if sign := eq.Gamma[i][j]; sign != 0 {
						lhs.add(&c[i][row], &d[j][col], sign)
					}
				}
			}
			rhs.add(&crs.U1[row], &proof.Pi[0][col], 1)
			rhs.add(&crs.U2[row], &proof.Pi[1][col], 1)
			rhs.add(&proof.Theta[0][row], &crs.V1[col], 1)
			rhs.add(&proof.Theta[1][row], &crs.V2[col], 1)
			if !gsPairEqual(lhs, rhs) {
				return false
			}
		}
	}
	return true
}

func gsVerifySchnorr(crs CaptureCRS, eq gsMSM1, proof gsMSM1Proof, c [12]gsVec1, ds [2]gsVec2) bool {
	scalars := [3]gsVec2{ds[0], ds[1], crs.w2()}
	for row := 0; row < 2; row++ {
		for col := 0; col < 2; col++ {
			var lhs, rhs capturePairs
			if row == 1 {
				for j := 0; j < 3; j++ {
					lhs.add(&eq.A[j], &scalars[j][col], 1)
				}
			}
			for i := 0; i < 12; i++ {
				for j := 0; j < 3; j++ {
					if coeff := eq.Gamma[i][j]; coeff.Active {
						cp := c[i][row]
						cp.MultAssign(&coeff.Scalar)
						lhs.add(&cp, &scalars[j][col], 1)
					}
				}
			}
			rhs.add(&crs.U1[row], &proof.Pi[0][col], 1)
			rhs.add(&crs.U2[row], &proof.Pi[1][col], 1)
			rhs.add(&proof.Theta[row], &crs.V1[col], 1)
			if !gsPairEqual(lhs, rhs) {
				return false
			}
		}
	}
	return true
}

func CaptureVerify(crs CaptureCRS, st *CaptureStatement, proof *CaptureProof) (bool, error) {
	if err := ValidateGlobalCaptureCRS(crs); err != nil {
		return false, err
	}
	if st == nil || proof == nil {
		return false, errors.New("nil statement/proof")
	}
	ppe, msm, err := captureEquations(st)
	if err != nil {
		return false, err
	}
	for i := 0; i < 4; i++ {
		if !gsVerifyPPE(crs, ppe[i], proof.PPE[i], proof.C, proof.D) {
			return false, nil
		}
	}
	for i := 0; i < 2; i++ {
		if !gsVerifySchnorr(crs, msm[i], proof.SchnorrMSM[i], proof.C, proof.ScalarD) {
			return false, nil
		}
	}
	if !verifyOpeningKnowledge(crs, st, proof) {
		return false, nil
	}
	return true, nil
}

// Compact serialization for JR PPEs plus two Schnorr MSM proofs.
// Group points are validated on decode.
const CaptureGSProofG1Count = 36
const CaptureGSProofG2Count = 28
const CaptureGSCoreBytes = CaptureGSProofG1Count*CompressedP1AffineSize + CaptureGSProofG2Count*CompressedP2AffineSize
const CaptureGSProofCompressedSize = CaptureGSCoreBytes + CaptureOpeningPoKBytes

func (p CaptureProof) marshalGSCore() ([]byte, error) {
	out := make([]byte, 0, CaptureGSCoreBytes)
	add1 := func(x *blst.P1) { out = append(out, x.ToAffine().Compress()...) }
	add2 := func(x *blst.P2) { out = append(out, x.ToAffine().Compress()...) }
	for i := range p.C {
		for j := 0; j < 2; j++ {
			add1(&p.C[i][j])
		}
	}
	for i := range p.D {
		for j := 0; j < 2; j++ {
			add2(&p.D[i][j])
		}
	}
	for i := range p.ScalarD {
		for j := 0; j < 2; j++ {
			add2(&p.ScalarD[i][j])
		}
	}
	for i := range p.PPE {
		if i < 2 {
			add2(&p.PPE[i].Pi[0][0])
			add2(&p.PPE[i].Pi[1][0])
			continue
		}
		for j := 0; j < 2; j++ {
			for k := 0; k < 2; k++ {
				add2(&p.PPE[i].Pi[j][k])
			}
		}
		for j := 0; j < 2; j++ {
			for k := 0; k < 2; k++ {
				add1(&p.PPE[i].Theta[j][k])
			}
		}
	}
	for i := range p.SchnorrMSM {
		for j := 0; j < 2; j++ {
			for k := 0; k < 2; k++ {
				add2(&p.SchnorrMSM[i].Pi[j][k])
			}
		}
		for j := 0; j < 2; j++ {
			add1(&p.SchnorrMSM[i].Theta[j])
		}
	}

	if len(out) != CaptureGSCoreBytes {
		return nil, fmt.Errorf("internal GS core size mismatch: %d != %d", len(out), CaptureGSCoreBytes)
	}
	return out, nil
}
func (p CaptureProof) MarshalBinary() ([]byte, error) {
	gs, err := p.marshalGSCore()
	if err != nil {
		return nil, err
	}
	pok, err := p.marshalOpeningPoK()
	if err != nil {
		return nil, err
	}
	gs = append(gs, pok...)
	if len(gs) != CaptureGSProofCompressedSize {
		return nil, fmt.Errorf("bad full proof size: %d", len(gs))
	}
	return gs, nil
}
func (p *CaptureProof) UnmarshalBinary(in []byte) error {
	if p == nil {
		return errors.New("nil proof")
	}
	// Fail closed: a failed decode must not leave an earlier valid proof
	// in a reused receiver. Decode into a temporary before assignment.
	*p = CaptureProof{}
	if len(in) != CaptureGSProofCompressedSize {
		return fmt.Errorf("invalid GS proof length %d", len(in))
	}
	var parsed CaptureProof
	pos := 0
	read1 := func(x *blst.P1) error {
		var a blst.P1Affine
		if a.Uncompress(in[pos:pos+CompressedP1AffineSize]) == nil || !a.InG1() {
			return errors.New("invalid G1 proof point")
		}
		*x = gsP1FromAff(&a)
		pos += CompressedP1AffineSize
		return nil
	}
	read2 := func(x *blst.P2) error {
		var a blst.P2Affine
		if a.Uncompress(in[pos:pos+CompressedP2AffineSize]) == nil || !a.InG2() {
			return errors.New("invalid G2 proof point")
		}
		*x = gsP2FromAff(&a)
		pos += CompressedP2AffineSize
		return nil
	}
	for i := range parsed.C {
		for j := 0; j < 2; j++ {
			if err := read1(&parsed.C[i][j]); err != nil {
				return err
			}
		}
	}
	for i := range parsed.D {
		for j := 0; j < 2; j++ {
			if err := read2(&parsed.D[i][j]); err != nil {
				return err
			}
		}
	}
	for i := range parsed.ScalarD {
		for j := 0; j < 2; j++ {
			if err := read2(&parsed.ScalarD[i][j]); err != nil {
				return err
			}
		}
	}
	for i := range parsed.PPE {
		if i < 2 {
			if err := read2(&parsed.PPE[i].Pi[0][0]); err != nil {
				return err
			}
			if err := read2(&parsed.PPE[i].Pi[1][0]); err != nil {
				return err
			}
			continue
		}
		for j := 0; j < 2; j++ {
			for k := 0; k < 2; k++ {
				if err := read2(&parsed.PPE[i].Pi[j][k]); err != nil {
					return err
				}
			}
		}
		for j := 0; j < 2; j++ {
			for k := 0; k < 2; k++ {
				if err := read1(&parsed.PPE[i].Theta[j][k]); err != nil {
					return err
				}
			}
		}
	}
	for i := range parsed.SchnorrMSM {
		for j := 0; j < 2; j++ {
			for k := 0; k < 2; k++ {
				if err := read2(&parsed.SchnorrMSM[i].Pi[j][k]); err != nil {
					return err
				}
			}
		}
		for j := 0; j < 2; j++ {
			if err := read1(&parsed.SchnorrMSM[i].Theta[j]); err != nil {
				return err
			}
		}
	}

	if pos != CaptureGSCoreBytes {
		return fmt.Errorf("GS proof core mismatch: %d", pos)
	}
	for i := 0; i < 2; i++ {
		for j := 0; j < 2; j++ {
			if err := read2(&parsed.OpeningPoK.T[i][j]); err != nil {
				return err
			}
		}
	}
	for i := 0; i < 2; i++ {
		for j := 0; j < 2; j++ {
			if parsed.OpeningPoK.Response[i][j].FromBEndian(in[pos:pos+ScalarSize]) == nil {
				return errors.New("invalid opening response scalar")
			}
			pos += ScalarSize
		}
	}
	if pos != len(in) {
		return fmt.Errorf("GS proof length mismatch: %d of %d", pos, len(in))
	}
	*p = parsed
	return nil
}

// CaptureVerifyBound verifies the CA3 signature on the manifest, recomputes
// the public capture message, then verifies the Groth–Sahai proof.
// IMPORTANT: T0 and the input raw bits must originate from an authenticated
// capture path; this function cannot verify physical sensor provenance.
func CaptureVerifyBound(
	crs CaptureCRS,
	raw []byte, bitCount int, manifest, timestamp []byte,
	ca3sig *ManifestCASignature, ca3VK *ManifestCAPublicKey,
	st *CaptureStatement, proof *CaptureProof,
) (bool, error) {
	if st == nil || proof == nil || ca3sig == nil || ca3VK == nil {
		return false, errors.New("missing capture artifact or CA3 certificate")
	}
	m, err := HashCaptureToG1(raw, bitCount, manifest, timestamp)
	if err != nil {
		return false, err
	}
	if !st.M.Equals(m.ToAffine()) {
		return false, nil
	}
	valid, err := VerifyManifestCASignature(ca3VK, manifest, ca3sig)
	if err != nil {
		return false, err
	}
	if !valid {
		return false, nil
	}
	return CaptureVerify(crs, st, proof)
}

const CaptureCRSCompressedSize = 4*CompressedP1AffineSize + 4*CompressedP2AffineSize

func (crs CaptureCRS) MarshalBinary() ([]byte, error) {
	out := make([]byte, 0, CaptureCRSCompressedSize)
	for _, v := range []gsVec1{crs.U1, crs.U2} {
		for i := 0; i < 2; i++ {
			out = append(out, v[i].ToAffine().Compress()...)
		}
	}
	for _, v := range []gsVec2{crs.V1, crs.V2} {
		for i := 0; i < 2; i++ {
			out = append(out, v[i].ToAffine().Compress()...)
		}
	}
	if len(out) != CaptureCRSCompressedSize {
		return nil, errors.New("internal CRS length mismatch")
	}
	return out, nil
}
func (crs *CaptureCRS) UnmarshalBinary(in []byte) error {
	if crs == nil {
		return errors.New("nil CRS")
	}
	// Fail closed for reused receivers; only commit fully decoded CRS.
	*crs = CaptureCRS{}
	if len(in) != CaptureCRSCompressedSize {
		return fmt.Errorf("invalid CRS length %d", len(in))
	}
	var decoded CaptureCRS
	off := 0
	for _, v := range []*gsVec1{&decoded.U1, &decoded.U2} {
		for i := 0; i < 2; i++ {
			var a blst.P1Affine
			if a.Uncompress(in[off:off+CompressedP1AffineSize]) == nil || !a.InG1() {
				return errors.New("invalid G1 CRS")
			}
			v[i] = gsP1FromAff(&a)
			off += CompressedP1AffineSize
		}
	}
	for _, v := range []*gsVec2{&decoded.V1, &decoded.V2} {
		for i := 0; i < 2; i++ {
			var a blst.P2Affine
			if a.Uncompress(in[off:off+CompressedP2AffineSize]) == nil || !a.InG2() {
				return errors.New("invalid G2 CRS")
			}
			v[i] = gsP2FromAff(&a)
			off += CompressedP2AffineSize
		}
	}
	*crs = decoded
	return nil
}

// CaptureVerifySerialized is the recommended entry point for untrusted proof
// bytes, because UnmarshalBinary validates each point and its subgroup.
func CaptureVerifySerialized(crs CaptureCRS, st *CaptureStatement, proofBytes []byte) (bool, error) {
	var proof CaptureProof
	if err := proof.UnmarshalBinary(proofBytes); err != nil {
		return false, err
	}
	return CaptureVerify(crs, st, &proof)
}
